#!/usr/bin/env python3
"""guide_render.py -- render guide/guide.json to guide/FIELD-GUIDE.md.

Usage:  python3 -I guide_render.py [--data F] [--out F|-] [--check] [--domains F]

Deterministic: the same input always gives the same bytes. The data is
validated first (lib/guide_schema.py); invalid data is never rendered.
--check renders in memory and exits 1 when the output file differs or is
missing. Python 3.9 stdlib only.
"""

import argparse
import os
import json
import re
import subprocess
import sys
import tempfile
from urllib.parse import urlsplit

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import guide_schema  # noqa: E402

FAMILY_TITLES = (
    ("claude", "Anthropic Claude family"),
    ("codex", "OpenAI Codex family"),
    ("gemini", "Google Gemini family (via Antigravity)"),
)
FAMILY_NAMES = {"claude": "Claude", "codex": "OpenAI", "gemini": "Gemini"}
DASH = "–"


def esc(text):
    """Escape the characters that change meaning in markdown tables and links."""
    out = []
    for ch in text:
        if ch in "\\|[]<>":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def link(url):
    host = urlsplit(url).hostname or url
    return "[%s](%s)" % (host, url)


def source_suffix(url):
    return " (%s)" % link(url) if url else ""


def sources_cell(urls):
    return ", ".join(link(u) for u in urls) if urls else DASH


def num(value):
    if value is None:
        return DASH
    if float(value) == int(value):
        return str(int(value))
    return "%.2f" % value


def price_cell(model):
    if model["price_in"] is None and model["price_out"] is None:
        base = DASH
    else:
        base = "%s / %s" % (num(model["price_in"]), num(model["price_out"]))
    note = model.get("price_note")
    if note:
        base += " (%s)" % esc(note)
    return base


def score_value(score):
    v = score["value"]
    return v if isinstance(v, str) else str(v)


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(r) + " |")
    return lines


def collect_sources(data):
    """Every distinct non-null source URL in the file, and the null count."""
    urls = set()
    nulls = [0]

    def add(u):
        if u is None:
            nulls[0] += 1
        else:
            urls.add(u)

    for row in data["bottom_line"]:
        for u in row["sources"] or [None]:
            add(u)
    for m in data["models"]:
        for s in m["scores"]:
            add(s["source"])
        for c in m["pros"] + m["cons"]:
            add(c["source"])
    for row in data.get("best_at", []):
        for u in row["sources"] or [None]:
            add(u)
    for n in data["reading_notes"]:
        add(n["source"])
    return sorted(urls), nulls[0]


def render(data):
    L = []
    L.append("# Frontier Model Field Guide: Claude, Codex and Gemini")
    L.append("")
    L.append("Facts checked %s. Generated from `guide/guide.json` by `kit-guide-render`; "
             "do not edit this file by hand." % data["checked"])
    L.append("")

    L.append("## Bottom line")
    L.append("")
    if data.get("summary"):
        L.append(esc(data["summary"]))
        L.append("")
    L.extend(table(
        ["Work", "Send to", "Why", "Sources"],
        [[esc(r["work"]), esc(r["send_to"]), esc(r["why"]), sources_cell(r["sources"])]
         for r in data["bottom_line"]],
    ))
    L.append("")

    benches = data.get("headline_benches", [])
    L.append("## Master comparison")
    L.append("")
    if data.get("comparison_note"):
        L.append(esc(data["comparison_note"]))
        L.append("")
    header = ["Model", "Price in / out, $ per M tokens"] + [esc(b) for b in benches] + ["Use for"]
    rows = []
    for m in data["models"]:
        cells = [esc(m["name"]), price_cell(m)]
        for b in benches:
            hit = None
            for s in m["scores"]:
                if s["bench"] == b:
                    hit = s
                    break
            if hit is None:
                cells.append(DASH)
            else:
                v = esc(score_value(hit))
                cells.append(v if hit["run_by"] == "independent" else v + " (vendor)")
        cells.append(esc(m["use_for"]))
        rows.append(cells)
    L.extend(table(header, rows))
    L.append("")

    fam_by_id = dict((f["id"], f) for f in data["families"])
    for fid, title in FAMILY_TITLES:
        models = [m for m in data["models"] if m["family"] == fid]
        fam = fam_by_id.get(fid)
        if not models and not fam:
            continue
        L.append("## " + title)
        L.append("")
        if fam and fam.get("summary"):
            L.append(esc(fam["summary"]))
            L.append("")
        if fam and fam.get("plans_note"):
            L.append("**Plans and pools:** " + esc(fam["plans_note"]))
            L.append("")
        for m in models:
            L.append("### %s (%s) · %s%s" % (
                esc(m["name"]), esc(m["released"]), m["id"],
                " (retired)" if m.get("retired") is True else ""))
            L.append("")
            L.append("Use for: " + esc(m["use_for"]))
            L.append("")
            if m.get("summary"):
                L.append(esc(m["summary"]))
                L.append("")
            if m["scores"]:
                L.append("Scores:")
                L.append("")
                for s in m["scores"]:
                    L.append("- %s: %s (%s run)%s" % (
                        esc(s["bench"]), esc(score_value(s)), s["run_by"],
                        source_suffix(s["source"])))
                L.append("")
            if m["pros"]:
                L.append("Pros:")
                L.append("")
                for c in m["pros"]:
                    L.append("- %s%s" % (esc(c["text"]), source_suffix(c["source"])))
                L.append("")
            if m["cons"]:
                L.append("Cons:")
                L.append("")
                for c in m["cons"]:
                    L.append("- %s%s" % (esc(c["text"]), source_suffix(c["source"])))
                L.append("")

    if data.get("best_at"):
        L.append("## Best at, by work type")
        L.append("")
        if data.get("best_at_note"):
            L.append(esc(data["best_at_note"]))
            L.append("")
        L.extend(table(
            ["Work type", "Best", "Runner-up", "Evidence", "Confidence", "Sources"],
            [[esc(r["work"]), esc(r["best"]), esc(r["runner_up"]), esc(r["evidence"]),
              esc(r["confidence"]), sources_cell(r["sources"])] for r in data["best_at"]],
        ))
        L.append("")

    L.append("## Family personalities and cross-family review")
    L.append("")
    if data.get("personalities_note"):
        L.append(esc(data["personalities_note"]))
        L.append("")
    L.extend(table(
        ["Family", "Tends to", "Watch for", "Brief it with"],
        [[FAMILY_NAMES[f["id"]], esc(f["tends_to"]), esc(f["watch_for"]), esc(f["brief_with"])]
         for f in sorted(data["families"], key=lambda f: [x[0] for x in FAMILY_TITLES].index(f["id"]))],
    ))
    L.append("")

    L.append("## How to read these numbers")
    L.append("")
    for n in data["reading_notes"]:
        L.append("- %s%s" % (esc(n["text"]), source_suffix(n["source"])))
    L.append("")

    urls, nulls = collect_sources(data)
    L.append("## Sources")
    L.append("")
    L.append("Every link below was opened and shows the fact it is attached to. "
             "%d fact(s) have no source yet." % nulls)
    L.append("")
    for u in urls:
        L.append("- " + link(u))
    L.append("")
    return "\n".join(L).rstrip("\n") + "\n"


def render_readme(path, here):
    """Replace example bodies, retaining every byte of owner text and markers."""
    with open(path, "rb") as f:
        original = f.read()
    lines = original.splitlines(keepends=True)
    output = []
    spec = None
    for line in lines:
        start = re.fullmatch(rb"<!-- example:start ([^\r\n]+) -->\r?\n", line)
        end = line.rstrip(b"\r\n") == b"<!-- example:end -->"
        if start:
            if spec is not None:
                raise ValueError("nested README example block")
            spec = start.group(1).decode("utf-8")
            output.append(line)
            profile = {"version": 1, "paseo": False}
            for pair in spec.split():
                key, value = pair.split("=", 1)
                if key in profile:
                    raise ValueError("duplicate README profile key: " + key)
                profile[key] = {"true": True, "false": False}.get(value, value)
            with tempfile.TemporaryDirectory(prefix="guide-example-") as tmp:
                profile_path = os.path.join(tmp, "profile.json")
                with open(profile_path, "w", encoding="utf-8") as f:
                    json.dump(profile, f)
                env = dict(os.environ, ROUTING_KIT_HOME=tmp, CODEX_HOME=os.path.join(tmp, "codex"))
                result = subprocess.run(
                    ["bash", os.path.join(here, "..", "bin", "kit-routing-table"),
                     "--profile", profile_path], env=env, stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE, check=True)
                output.append(result.stdout.rstrip(b"\n") + b"\n")
        elif end:
            if spec is None:
                raise ValueError("README example end without start")
            spec = None
            output.append(line)
        elif spec is None:
            output.append(line)
    if spec is not None:
        raise ValueError("unclosed README example block")
    return b"".join(output)


def write_atomic(path, payload):
    out_dir = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(prefix=".kit-guide-render.", dir=out_dir)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(payload)
        mask = os.umask(0)
        os.umask(mask)
        os.chmod(tmp, 0o666 & ~mask)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    guide_dir = os.path.join(here, "..", "guide")
    ap = argparse.ArgumentParser(prog="kit-guide-render", add_help=True)
    ap.add_argument("--data", default=os.path.join(guide_dir, "guide.json"))
    ap.add_argument("--out", default=os.path.join(guide_dir, "FIELD-GUIDE.md"))
    ap.add_argument("--domains", default=os.path.join(guide_dir, "source-domains.txt"))
    ap.add_argument("--readme", help="README examples to render (default: repo README for the default guide)")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv[1:])
    if args.check and args.out == "-":
        sys.stderr.write("kit-guide-render: --check needs a file, not --out -\n")
        return 2
    try:
        domains = guide_schema.load_domains(args.domains)
        data = guide_schema.load_json(args.data)
    except (OSError, ValueError, RecursionError) as e:
        sys.stderr.write("kit-guide-render: cannot read input: %s\n" % e)
        return 2
    errors, _warnings = guide_schema.validate(data, domains)
    if errors:
        for e in errors:
            sys.stderr.write("%s\n" % e)
        sys.stderr.write("kit-guide-render: %s is invalid; nothing rendered\n" % args.data)
        return 1
    text = render(data)
    payload = text.encode("utf-8")
    if args.out == "-":
        sys.stdout.buffer.write(payload)
        return 0
    outputs = [(args.out, payload)]
    readme = args.readme
    # Explicit guide inputs/outputs remain useful for standalone fixture renders.
    if readme is None and not any(a in argv[1:] for a in ("--data", "--out")):
        candidate = os.path.abspath(os.path.join(here, "..", "..", "..", "README.md"))
        if os.path.isfile(candidate):
            readme = candidate
    if readme is not None:
        try:
            outputs.append((readme, render_readme(readme, here)))
        except (OSError, ValueError, subprocess.CalledProcessError) as e:
            sys.stderr.write("kit-guide-render: cannot render README examples: %s\n" % e)
            return 1
    stale = False
    for path, content in outputs:
        if args.check:
            try:
                with open(path, "rb") as f:
                    current = f.read()
            except OSError:
                current = None
            if current != content:
                sys.stderr.write("kit-guide-render: %s is out of date; run kit-guide-render\n" % path)
                stale = True
        else:
            write_atomic(path, content)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
